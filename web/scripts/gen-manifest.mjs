// Builds the sprite registry from what is on disk:
//   assets/clawd/manifest.json        the registry shipped next to the images
//   web/src/manifest.generated.ts     the same registry compiled into the element as its default
// Run it again whenever files are added to or removed from assets/clawd/.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pack = join(here, "..", "..", "assets", "clawd");
// The order matters: a pot picks outfits[hash(pot id) % outfits.length].
const OUTFITS = ["toque", "scarf"];

const files = {};
for (const outfit of OUTFITS) {
  for (const name of readdirSync(join(pack, outfit)).sort()) {
    const m = /^(.+)\.(webp|png)$/.exec(name);
    if (m) files[`${outfit}/${m[1]}`] = `${outfit}/${name}`;
  }
}
const manifest = { name: "clawd", outfits: OUTFITS, files };
writeFileSync(join(pack, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
writeFileSync(
  join(here, "..", "src", "manifest.generated.ts"),
  "// Generated by scripts/gen-manifest.mjs from assets/clawd/. Do not edit by hand; run `npm run manifest`.\n" +
    'import type { SpriteManifest } from "./manifest";\n\n' +
    `export const CLAWD_MANIFEST: SpriteManifest = ${JSON.stringify(manifest, null, 2)};\n`,
);
console.log(`${Object.keys(files).length} files registered for ${OUTFITS.join(", ")}`);
