#!/usr/bin/env python3
"""Cuts the fonts the kitchen page ships, as WOFF2, and writes public/fonts.css.

Noto Serif SC (weights 400 and 300), two parts per weight:

  <name>.common.woff2   everything that is not a Han character (Latin, punctuation, kana, symbols)
                        plus the 3755 most common Han characters (GB 2312 level 1)
  <name>.rare.woff2     every other Han character in the source font

A browser downloads a part only when a character on the page needs it, and none at all when the
device already has Noto Serif SC / Source Han Serif SC installed.

Bodoni Moda (weight 400; the 11 pt, 28 pt and 96 pt optical sizes): Basic Latin and Latin-1 only
(the page sets numbers, "%", "/" and "×" in it).

Needs: Python 3 with fonttools and brotli (`pip install fonttools brotli`).
Usage:
  python3 scripts/subset_fonts.py <NotoSerifSC-Regular.ttf> <NotoSerifSC-Light.ttf> \
      <BodoniModa11pt-Regular.ttf> <BodoniModa28pt-Regular.ttf> <BodoniModa-Regular.ttf>

The Bodoni optical sizes are static instances of the Bodoni Moda variable font (opsz 11 / 28 / 96, wght 400).
"""
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

PAGE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(PAGE, "public", "fonts")


def gb2312_level1():
    out = set()
    for hi in range(0xB0, 0xD8):
        for lo in range(0xA1, 0xFF):
            try:
                out.add(ord(bytes([hi, lo]).decode("gb2312")))
            except UnicodeDecodeError:
                pass
    return out


def is_han(c):
    return 0x3400 <= c <= 0x4DBF or 0x4E00 <= c <= 0x9FFF or 0xF900 <= c <= 0xFAFF


def cut(src, codepoints, name):
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.notdef_outline = True
    font = TTFont(src)
    s = subset.Subsetter(options)
    s.populate(unicodes=codepoints)
    s.subset(font)
    font.flavor = "woff2"
    out = os.path.join(OUT, name)
    font.save(out)
    print(name, os.path.getsize(out), "bytes,", len(codepoints), "characters")


def ranges(codepoints):
    cs = sorted(codepoints)
    out, a, b = [], cs[0], cs[0]
    for c in cs[1:]:
        if c == b + 1:
            b = c
        else:
            out.append((a, b))
            a = b = c
    out.append((a, b))
    return ",".join(f"U+{x:X}" if x == y else f"U+{x:X}-{y:X}" for x, y in out)


SERIF = (
    # family the page asks for, file stem, names an installed copy may go by
    ("Kitchenette Serif", "NotoSerifSC-Regular",
     ["Noto Serif SC", "Noto Serif SC Regular", "NotoSerifSC-Regular", "Source Han Serif SC",
      "Source Han Serif SC Regular", "SourceHanSerifSC-Regular", "Noto Serif CJK SC", "NotoSerifCJKsc-Regular"]),
    ("Kitchenette Serif Light", "NotoSerifSC-Light",
     ["Noto Serif SC Light", "NotoSerifSC-Light", "Source Han Serif SC Light", "SourceHanSerifSC-Light",
      "Noto Serif CJK SC Light", "NotoSerifCJKsc-Light"]),
)
BODONI = (
    ("Kitchenette Bodoni 11", "BodoniModa11pt-Regular"),
    ("Kitchenette Bodoni 28", "BodoniModa28pt-Regular"),
    ("Kitchenette Bodoni 96", "BodoniModa96pt-Regular"),
)


def main():
    if len(sys.argv) != 6:
        sys.exit(__doc__)
    os.makedirs(OUT, exist_ok=True)
    level1 = gb2312_level1()
    css = ["/* Generated by scripts/subset_fonts.py. Do not edit by hand. */",
           "/* An installed copy of the font is used first; a file is fetched only when a character needs it. */"]
    for src, (family, stem, local) in zip(sys.argv[1:3], SERIF):
        cps = set(TTFont(src).getBestCmap())
        common = {c for c in cps if not is_han(c) or c in level1}
        rare = cps - common
        cut(src, common, f"{stem}.common.woff2")
        cut(src, rare, f"{stem}.rare.woff2")
        locals_ = ", ".join(f'local("{n}")' for n in local)
        for part, extra in (("common", ""), ("rare", f" unicode-range: {ranges(rare)};")):
            css.append(f'@font-face {{ font-family: "{family}"; font-weight: 400; font-style: normal; font-display: swap; '
                       f'src: {locals_}, url("fonts/{stem}.{part}.woff2") format("woff2");{extra} }}')
    latin = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100))
    for src, (family, stem) in zip(sys.argv[3:6], BODONI):
        cut(src, latin & set(TTFont(src).getBestCmap()), f"{stem}.woff2")
        css.append(f'@font-face {{ font-family: "{family}"; font-weight: 400; font-style: normal; font-display: swap; '
                   f'src: url("fonts/{stem}.woff2") format("woff2"); }}')
    with open(os.path.join(PAGE, "public", "fonts.css"), "w", encoding="utf-8") as f:
        f.write("\n".join(css) + "\n")
    print("public/fonts.css written")


if __name__ == "__main__":
    main()
