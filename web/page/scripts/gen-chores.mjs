// Writes src/kitchen/choreArt.generated.ts: the chore clips of the cook (assets/clawd/<outfit>/, the same
// files the cooking card plays from) for the panels of the sheet, plus the still base pose.
// The page uses them from there rather than keeping a second copy (metro.config.js watches the folder).
// Usage: node scripts/gen-chores.mjs     (run from web/page/ after the sprite pack changed)
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const page = join(dirname(fileURLToPath(import.meta.url)), "..");
const pack = join(page, "..", "..", "assets", "clawd");
const OUTFITS = ["toque", "scarf"];
const SEGMENTS = [
  "vendor_call", "vendor_pay", "vendor_take", "vendor_take_last", "vendor_carry",
  "dish_sleeve", "dish_soap", "dish_scrub", "dish_rinse", "dish_shake", "dish_dry", "dish_stack", "dish_break", "dish_break_last",
  "machine_load", "machine_close", "machine_start", "machine_run", "machine_done", "machine_done_last",
  "base",
];
const rows = [];
for (const o of OUTFITS) {
  rows.push(`  ${o}: {`);
  for (const s of SEGMENTS) {
    const file = [`${s}.webp`, `${s}.png`].find((f) => existsSync(join(pack, o, f)));
    if (!file) throw new Error(`assets/clawd/${o}/${s}.{webp,png} is missing`);
    rows.push(`    ${s}: require("../../../../assets/clawd/${o}/${file}"),`);
  }
  rows.push("  },");
}
writeFileSync(join(page, "src", "kitchen", "choreArt.generated.ts"), `// Generated by scripts/gen-chores.mjs from assets/clawd/: do not edit by hand.
// The cook's chore clips (animated WebP, 720 x 720, the counter line at y = 560) and the still frames.
// Clawd artwork: CC BY-NC-SA 4.0, see assets/clawd/ATTRIBUTION.md.
import type { ImageSourcePropType } from "react-native";

export const CHORE_SEGMENTS = ${JSON.stringify(SEGMENTS)} as const;
export type ChoreSegment = (typeof CHORE_SEGMENTS)[number];

export const CHORE_ART: Record<"toque" | "scarf", Record<ChoreSegment, ImageSourcePropType>> = {
${rows.join("\n")}
};
`);
console.log(`choreArt.generated.ts: ${OUTFITS.length} outfits x ${SEGMENTS.length}`);
