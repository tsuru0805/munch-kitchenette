// Writes src/kitchen/sceneArt.generated.ts: the kitchen picture in three lights (day / dusk / night) and
// the cut-out pieces that are put back onto it (the flower on the sill, the three jars, the drying rack,
// the sink), with where each piece goes.
// The pictures are the ones of the online demo (docs/play/img/), used from that one folder: the page
// requires them from there instead of keeping a second copy. Where each piece goes is read from the
// demo page itself (docs/play/index.html, `const D=`: left / top / width / height in percent of the
// square), so the demo and the page cannot drift apart.
// Usage: node scripts/gen-scene.mjs     (run from web/page/ after docs/play/ was rebuilt)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const page = join(dirname(fileURLToPath(import.meta.url)), "..");
const demo = join(page, "..", "..", "docs", "play");
const html = readFileSync(join(demo, "index.html"), "utf8");
const m = html.match(/const D=(\{.*?\});/);
if (!m) throw new Error("docs/play/index.html: no `const D={...};` found");
const D = JSON.parse(m[1]);
const SRC = 1254; // the square the page measures everything on (sceneSlots.ts SCENE_SRC)
const px = (pct) => Math.round(pct * SRC) / 100;
const rel = "../../../../docs/play/";

const keys = Object.keys(D).sort();
const rows = keys.map((k) => {
  const [file, x, y, w, h] = D[k];
  if (!/^img\/[a-z0-9_]+\.webp$/.test(file)) throw new Error(`${k}: unexpected file ${file}`);
  return `  "${k}": { src: require("${rel}${file}"), x: ${px(x)}, y: ${px(y)}, w: ${px(w)}, h: ${px(h)} },`;
});
const out = `// Generated by scripts/gen-scene.mjs from docs/play/ (the online demo): do not edit by hand.
// The kitchen in three lights and the pieces put back onto it. x / y / w / h = where a piece goes, in
// pixels of the 1254 px square (as in sceneSlots.ts); the piece is stretched to exactly that box.
import type { ImageSourcePropType } from "react-native";

export type Light = "day" | "dusk" | "night";
export const LIGHTS: Light[] = ["day", "dusk", "night"];

export const SCENE_BASE: Record<Light, ImageSourcePropType> = {
  day: require("${rel}img/base_day.webp"),
  dusk: require("${rel}img/base_dusk.webp"),
  night: require("${rel}img/base_night.webp"),
};

export interface ScenePiece { src: ImageSourcePropType; x: number; y: number; w: number; h: number }

/** "<light>_<sheet>_<n>": sheet fl1 / fl2 = flowers (three kinds × fresh / droopy / wilted), jars = jar 1–3 × empty / fruit / pickles, dish 1–3 = the rack, 4–7 = the sink */
export const SCENE_PIECES: Record<string, ScenePiece> = {
${rows.join("\n")}
};
`;
writeFileSync(join(page, "src", "kitchen", "sceneArt.generated.ts"), out);
console.log(`sceneArt.generated.ts: ${keys.length} pieces`);
