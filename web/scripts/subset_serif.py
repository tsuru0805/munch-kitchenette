#!/usr/bin/env python3
"""Cuts the bundled serif (Noto Serif SC) for the card: WOFF2, two parts per weight.

  <name>.common.woff2   everything that is not a Han character (Latin, punctuation, kana, symbols)
                        plus the 3755 most common Han characters (GB 2312 level 1)
  <name>.rare.woff2     every other Han character in the source font

A browser downloads a part only when a character on the card needs it, so most cards never fetch
the rare part. The ranges of the rare part are written to src/serifRange.generated.ts.

Needs: Python 3 with fonttools and brotli (`pip install fonttools brotli`).
Usage: python3 scripts/subset_serif.py <NotoSerifSC Regular .ttf> <NotoSerifSC Bold .ttf>
"""
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

WEB = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def gb2312_level1():
    out = set()
    for hi in range(0xB0, 0xD8):
        for lo in range(0xA1, 0xFF):
            try:
                out.add(ord(bytes([hi, lo]).decode("gb2312")))
            except UnicodeDecodeError:
                pass
    return out


def is_han(c):
    return 0x3400 <= c <= 0x4DBF or 0x4E00 <= c <= 0x9FFF or 0xF900 <= c <= 0xFAFF


def cut(src, codepoints, out):
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.notdef_outline = True
    font = TTFont(src)
    s = subset.Subsetter(options)
    s.populate(unicodes=codepoints)
    s.subset(font)
    font.flavor = "woff2"
    font.save(out)
    print(os.path.relpath(out, WEB), os.path.getsize(out), "bytes,", len(codepoints), "characters")


def ranges(codepoints):
    cs = sorted(codepoints)
    out, a, b = [], cs[0], cs[0]
    for c in cs[1:]:
        if c == b + 1:
            b = c
        else:
            out.append((a, b))
            a = b = c
    out.append((a, b))
    return ",".join(f"U+{x:X}" if x == y else f"U+{x:X}-{y:X}" for x, y in out)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    level1 = gb2312_level1()
    rare_all = None
    for src, name in zip(sys.argv[1:], ("NotoSerifSC-Regular", "NotoSerifSC-Bold")):
        cps = set(TTFont(src).getBestCmap())
        common = {c for c in cps if not is_han(c) or c in level1}
        rare = cps - common
        assert rare_all in (None, rare), "the two weights cover different characters"
        rare_all = rare
        cut(src, common, os.path.join(WEB, "fonts", f"{name}.common.woff2"))
        cut(src, rare, os.path.join(WEB, "fonts", f"{name}.rare.woff2"))
    with open(os.path.join(WEB, "src", "serifRange.generated.ts"), "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/subset_serif.py. Do not edit by hand.\n"
                "// The characters in the bundled serif's `rare` part: every Han character outside GB 2312 level 1.\n"
                f'export const SERIF_RARE_RANGE =\n  "{ranges(rare_all)}";\n')


if __name__ == "__main__":
    main()
